def load_source():
    rows = list(csv.reader(io.open(CSV_PATH, encoding="utf-8")))
    by_idx = {}
    for row in rows[1:]:
        if len(row) < 4:
            continue
        glyph, idx, han, pron = row[0].strip(), int(row[1]), row[2].strip(), row[3].strip()
        by_idx[idx] = {"g": glyph, "i": idx, "h": han, "p": pron}
    if len(by_idx) != TOTAL:
        raise SystemExit("源表应有 %d 个字，实际读到 %d 个" % (TOTAL, len(by_idx)))
    return by_idx


def build_entries(source):
    if len(ENTRIES) != 144:
        raise SystemExit("帘上应取 144 字，当前 %d 字" % len(ENTRIES))
    seen_glyph, seen_focus, seen_idx = set(), set(), set()
    out = []
    for focus, idx in ENTRIES:
        if idx not in source:
            raise SystemExit("《字帖》序 %d 不在源表中" % idx)
        row = source[idx]
        han = "".join(dict.fromkeys(row["h"]))
        if focus not in han:
            raise SystemExit("取义「%s」不在序 %d 的对应汉字「%s」里" % (focus, idx, han))
        if focus in seen_focus:
            raise SystemExit("取义重复：%s" % focus)
        if row["g"] in seen_glyph:
            raise SystemExit("女书字形重复：U+%05X" % ord(row["g"]))
        if idx in seen_idx:
            raise SystemExit("《字帖》序重复：%d" % idx)
        if focus not in GLOSS:
            raise SystemExit("缺释义：%s" % focus)
        seen_glyph.add(row["g"])
        seen_focus.add(focus)
        seen_idx.add(idx)
        out.append({
            "g": row["g"],
            "i": idx,
            "p": row["p"],
            "h": han,
            "f": focus,
            "d": GLOSS[focus],
        })
    return out


def write_js(entries):
    shuffled = entries[:]
    random.Random(20261028).shuffle(shuffled)
    payload = {
        "meta": {
            "total": TOTAL,
            "shown": len(shuffled),
            "source": "赵丽明、徐焰编纂《女书规范字书法字帖》（Unicode 标准）· Nushu Developers Workgroup 整理",
            "url": "https://nushuscript.org/",
            "data": "https://github.com/nushu-script/unicode_nushu",
        },
        "entries": shuffled,
    }
    header = (
        "/* 女书字帘 / 字典数据（由 themes/scripts/build_nushu_dict.py 生成，勿手改）\n"
        "   数据：Nushu Developers Workgroup《女书规范字书法字帖》(Unicode 标准)\n"
        "   来源：https://nushuscript.org/ · https://github.com/nushu-script/unicode_nushu\n"
        "   396 个标准字中取 144 字，每个女书字形只出现一次。\n"
        "   字段：g=女书字 i=字帖序 p=江永方言发音 h=全部对应汉字 f=本页取义 d=释义 */\n"
    )
    body = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    OUT_JS.write_text(header + "window.NUSHU_DICT=" + body + ";\n", encoding="utf-8")
    print("written", OUT_JS, OUT_JS.stat().st_size, "bytes")


def write_font(entries):
    glyphs = "".join(e["g"] for e in entries)
    text_file = ASSETS / "data" / "_nushu_subset.txt"
    text_file.write_text(glyphs, encoding="utf-8")
    cmd = [
        "pyftsubset", str(FONT_SRC),
        "--text-file=" + str(text_file),
        "--flavor=woff2",
        "--no-hinting",
        "--output-file=" + str(OUT_FONT),
    ]
    subprocess.run(cmd, check=True)
    text_file.unlink()
    print("written", OUT_FONT, OUT_FONT.stat().st_size, "bytes")


def main():
    source = load_source()
    entries = build_entries(source)
    write_js(entries)
    write_font(entries)


if __name__ == "__main__":
    main()
